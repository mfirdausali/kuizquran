// EVERY FACT HERE WAS VERIFIED AGAINST THE VENDORED SOURCE, NOT RECALLED
// ---------------------------------------------------------------------------
// The source of truth is `v1/data/raw/SOURCES.md`, which records what was
// actually vendored, from where, and under what licence. Version numbers,
// attribution names and licence names below are copied from there rather than
// from memory, because an attribution page that misattributes is worse than
// none: it is a false statement about someone else's work.
//
// WHAT IS DELIBERATELY NOT CLAIMED HERE:
//   - No claim that the Quran text is licensed by anyone. It is not — the text
//     may be copied and distributed verbatim, and SOURCES.md says exactly that.
//     The licence discussion concerns the ANNOTATIONS only.
//   - No claim of endorsement, review or approval by any source project. A
//     project whose data you used has not thereby blessed your product.
//   - No scholarly claim of any kind. Those belong to the qari gate and are
//     human-only forever.
//
// This is a copy module, not markup, for the same reason `lib/landing/copy.ts`
// is: strings that make claims are DATA, so they can be read by a test.

export interface AttributionSource {
  /** The project's own name for itself. */
  readonly name: string;
  /** What this product actually used it for — specific, never vague. */
  readonly used: string;
  /** The licence, named exactly as the project names it. */
  readonly licence: string;
  /** Canonical project URL. */
  readonly url: string;
  /** Named authors/maintainers, where the source names them. */
  readonly credit?: string;
  /** Anything a reader needs to correctly interpret the licence line. */
  readonly note?: string;
}

