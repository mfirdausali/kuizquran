/**
 * Every attribution string, flat — the shape `lib/landing/copy.ts#landingStrings`
 * uses, so a test can read the page's claims as data instead of scraping markup.
 */
export function attributionStrings(): string[] {
  const out: string[] = [];
  const walk = (value: unknown): void => {
    if (typeof value === "string") {
      out.push(value);
      return;
    }
    if (Array.isArray(value)) {
      value.forEach(walk);
      return;
    }
    if (value && typeof value === "object") {
      Object.values(value).forEach(walk);
    }
  };
  walk([PAGE, SOURCES, FONTS, BOUNDARIES, CORRECTIONS]);
  return out;
}
